-- 2. Private storage cleanup queue & helper functions (B8 & B10)
create table if not exists private.storage_cleanup_queue (
  id bigint generated by default as identity primary key,
  bucket_id text not null check (bucket_id in ('avatars', 'issue-media')),
  object_name text not null,
  owner_id uuid not null,
  reason text not null,
  status text not null default 'PENDING' check (status in ('PENDING', 'PROCESSING', 'COMPLETED', 'FAILED', 'SKIPPED_REFERENCED', 'SKIPPED_INVALID')),
  attempts integer not null default 0,
  last_error text,
  next_attempt_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (bucket_id, object_name)
);

create index if not exists storage_cleanup_queue_due_idx
  on private.storage_cleanup_queue (status, next_attempt_at);

create or replace function private.extract_owned_storage_object_path(
  p_url text,
  p_bucket text,
  p_owner_id uuid
)
returns text
language plpgsql
immutable
security definer
set search_path = ''
as $$
declare
  v_marker text := '/storage/v1/object/public/' || p_bucket || '/';
  v_pos integer;
  v_rel text;
begin
  if p_url is null or p_bucket is null or p_owner_id is null then
    return null;
  end if;

  v_pos := strpos(p_url, v_marker);
  if v_pos <= 0 then
    return null;
  end if;

  v_rel := substring(p_url from (v_pos + char_length(v_marker)));
  v_rel := split_part(split_part(v_rel, '?', 1), '#', 1);

  if v_rel ~ ('^' || p_owner_id::text || '/[0-9a-fA-F-]{36}\.jpg$') then
    return v_rel;
  end if;

  return null;
end;
$$;

create or replace function public.is_storage_object_referenced(
  p_bucket_id text,
  p_object_name text
)
returns boolean
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_suffix text := '/storage/v1/object/public/' || p_bucket_id || '/' || p_object_name;
begin
  if p_bucket_id = 'avatars' then
    return exists (
      select 1
      from public.profiles p
      where p.avatar_url is not null
        and split_part(split_part(p.avatar_url, '?', 1), '#', 1) like '%' || v_suffix
    );
  elsif p_bucket_id = 'issue-media' then
    return exists (
      select 1
      from public.issues i,
           unnest(i.media_urls) as u(url)
      where split_part(split_part(u.url, '?', 1), '#', 1) like '%' || v_suffix
    );
  end if;
  return false;
end;
$$;

