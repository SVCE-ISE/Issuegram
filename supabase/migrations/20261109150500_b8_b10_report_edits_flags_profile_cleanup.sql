-- 4. Profile UPDATE validation, public author consistency propagation, and avatar cleanup (B10)
create or replace function public.before_profile_update()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  caller_uid uuid := (select auth.uid());
  v_avatar_path text;
begin
  if current_user in ('postgres', 'service_role') and caller_uid is null then
    return new;
  end if;

  if caller_uid is null or old.id is distinct from caller_uid then
    raise exception 'Permission denied to update profile' using errcode = '42501';
  end if;

  if new.id is distinct from old.id
     or new.username is distinct from old.username
     or new.created_at is distinct from old.created_at
     or new.is_fixture is distinct from old.is_fixture then
    raise exception 'Cannot modify immutable profile identity fields' using errcode = '42501';
  end if;

  new.display_name := btrim(coalesce(new.display_name, ''));
  if new.display_name = '' then
    new.display_name := old.username;
  end if;

  if char_length(new.display_name) < 1 or char_length(new.display_name) > 36 then
    raise exception 'Display name must be 1 to 36 characters' using errcode = '22023';
  end if;

  if new.avatar_url is not null then
    new.avatar_url := btrim(new.avatar_url);
    if new.avatar_url = '' then
      new.avatar_url := null;
    else
      v_avatar_path := private.extract_owned_storage_object_path(new.avatar_url, 'avatars', old.id);
      if v_avatar_path is null then
        raise exception 'Avatar URL must reference an owned object in the avatars bucket' using errcode = '22023';
      end if;
    end if;
  end if;

  return new;
end;
$$;

do $$
begin
  if not exists (
    select 1 from pg_trigger
    where not tgisinternal
      and tgrelid = 'public.profiles'::regclass
      and tgname = 'tr_before_profile_update'
  ) then
    create trigger tr_before_profile_update
      before update on public.profiles
      for each row
      execute function public.before_profile_update();
  end if;
end $$;

create or replace function public.after_profile_update_propagate()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_old_avatar_path text;
begin
  if new.avatar_url is distinct from old.avatar_url or new.username is distinct from old.username then
    perform set_config('issuegram.profile_propagation', 'on', true);
    update public.issues
    set author_avatar_url = new.avatar_url,
        author_username = new.username
    where author_id = new.id
      and (author_avatar_url is distinct from new.avatar_url or author_username is distinct from new.username);
    perform set_config('issuegram.profile_propagation', 'off', true);
  end if;

  if new.username is distinct from old.username then
    update public.channel_messages
    set sender_username = new.username
    where sender_id = new.id
      and sender_username is distinct from new.username;
  end if;

  if old.avatar_url is not null and new.avatar_url is distinct from old.avatar_url then
    v_old_avatar_path := private.extract_owned_storage_object_path(old.avatar_url, 'avatars', old.id);
    if v_old_avatar_path is not null then
      perform private.enqueue_storage_cleanup('avatars', v_old_avatar_path, old.id, 'avatar_replaced_or_cleared');
      perform private.dispatch_storage_cleanup_worker();
    end if;
  end if;

  return new;
end;
$$;

do $$
begin
  if not exists (
    select 1 from pg_trigger
    where not tgisinternal
      and tgrelid = 'public.profiles'::regclass
      and tgname = 'tr_after_profile_update_propagate'
  ) then
    create trigger tr_after_profile_update_propagate
      after update on public.profiles
      for each row
      execute function public.after_profile_update_propagate();
  end if;
end $$;

