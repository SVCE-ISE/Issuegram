create or replace function public.before_issue_flag_insert()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  caller_uid uuid := (select auth.uid());
  v_issue_author uuid;
  v_is_fixture boolean;
  v_recent_count integer;
begin
  if caller_uid is null or new.reporter_id is distinct from caller_uid then
    raise exception 'Unauthorized flag reporter' using errcode = '42501';
  end if;

  if new.reason is null or new.reason not in (
    'Spam or advertising',
    'Harmful or private content',
    'Misleading report',
    'Duplicate report'
  ) then
    raise exception 'Invalid flag reason' using errcode = '22023';
  end if;

  if exists (
    select 1
    from public.issue_flags f
    where f.issue_id = new.issue_id
      and f.reporter_id = caller_uid
  ) then
    new.moderation_status := 'PENDING';
    new.reviewed_by := null;
    new.reviewed_at := null;
    new.review_notes := null;
    new.created_at := now();
    new.updated_at := new.created_at;
    return new;
  end if;

  select author_id, is_fixture
  into v_issue_author, v_is_fixture
  from public.issues
  where id = new.issue_id;

  if v_issue_author is null or v_is_fixture then
    raise exception 'Issue not found' using errcode = '23503';
  end if;

  if v_issue_author = caller_uid then
    raise exception 'Cannot flag your own report' using errcode = '22023';
  end if;

  select count(*)
  into v_recent_count
  from public.issue_flags f
  where f.reporter_id = caller_uid
    and f.created_at >= now() - interval '10 minutes';

  if v_recent_count >= 10 then
    raise exception 'Too many flags submitted recently. Please wait before submitting more.' using errcode = '42501';
  end if;

  new.moderation_status := 'PENDING';
  new.reviewed_by := null;
  new.reviewed_at := null;
  new.review_notes := null;
  new.created_at := now();
  new.updated_at := new.created_at;

  return new;
end;
$$;

do $$
begin
  if not exists (
    select 1 from pg_trigger
    where not tgisinternal
      and tgrelid = 'public.issue_flags'::regclass
      and tgname = 'tr_before_issue_flag_insert'
  ) then
    create trigger tr_before_issue_flag_insert
      before insert on public.issue_flags
      for each row
      execute function public.before_issue_flag_insert();
  end if;
end $$;

create or replace function public.before_issue_flag_update()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  caller_uid uuid := (select auth.uid());
begin
  if current_user in ('postgres', 'service_role') and caller_uid is null then
    return new;
  end if;

  if not private.is_moderator() then
    raise exception 'Only authorized moderators can review flags' using errcode = '42501';
  end if;

  if new.id is distinct from old.id
     or new.issue_id is distinct from old.issue_id
     or new.reporter_id is distinct from old.reporter_id
     or new.reason is distinct from old.reason
     or new.created_at is distinct from old.created_at then
    raise exception 'Cannot modify immutable flag fields' using errcode = '42501';
  end if;

  if new.moderation_status not in ('PENDING', 'REVIEWED_KEPT', 'REVIEWED_ACTIONED', 'DISMISSED') then
    raise exception 'Invalid moderation status' using errcode = '22023';
  end if;

  new.reviewed_by := caller_uid;
  new.reviewed_at := clock_timestamp();
  new.updated_at := new.reviewed_at;

  return new;
end;
$$;

do $$
begin
  if not exists (
    select 1 from pg_trigger
    where not tgisinternal
      and tgrelid = 'public.issue_flags'::regclass
      and tgname = 'tr_before_issue_flag_update'
  ) then
    create trigger tr_before_issue_flag_update
      before update on public.issue_flags
      for each row
      execute function public.before_issue_flag_update();
  end if;
end $$;

create or replace function public.after_issue_flag_update_audit()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  caller_uid uuid := coalesce((select auth.uid()), new.reviewed_by);
begin
  if (new.moderation_status is distinct from old.moderation_status or new.review_notes is distinct from old.review_notes)
     and caller_uid is not null then
    insert into public.moderation_audit_log (flag_id, issue_id, moderator_id, action, notes, created_at)
    values (
      new.id,
      new.issue_id,
      caller_uid,
      case
        when new.moderation_status = 'PENDING' then 'REOPENED_FLAG'
        else new.moderation_status
      end,
      new.review_notes,
      new.updated_at
    );
  end if;
  return new;
end;
$$;

