create or replace function private.enqueue_storage_cleanup(
  p_bucket_id text,
  p_object_name text,
  p_owner_id uuid,
  p_reason text
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if p_bucket_id not in ('avatars', 'issue-media') or p_object_name is null or p_owner_id is null then
    return;
  end if;

  if not (p_object_name ~ ('^' || p_owner_id::text || '/[0-9a-fA-F-]{36}\.jpg$')) then
    return;
  end if;

  insert into private.storage_cleanup_queue (
    bucket_id, object_name, owner_id, reason, status, attempts, last_error, next_attempt_at, updated_at
  ) values (
    p_bucket_id, p_object_name, p_owner_id, p_reason, 'PENDING', 0, null, now(), now()
  )
  on conflict (bucket_id, object_name) do update
  set status = 'PENDING',
      owner_id = excluded.owner_id,
      reason = excluded.reason,
      attempts = 0,
      last_error = null,
      next_attempt_at = now(),
      updated_at = now();
end;
$$;

create or replace function public.claim_storage_cleanup_jobs(p_limit integer default 25)
returns table (
  id bigint,
  bucket_id text,
  object_name text,
  owner_id uuid,
  attempts integer
)
language plpgsql
security definer
set search_path = ''
as $$
begin
  return query
  with due as (
    select q.id
    from private.storage_cleanup_queue q
    where (
      q.status = 'PENDING'
      and q.next_attempt_at <= now()
      and q.attempts < 8
    ) or (
      q.status = 'PROCESSING'
      and q.updated_at <= now() - interval '2 minutes'
      and q.attempts < 8
    )
    order by q.next_attempt_at asc, q.id asc
    limit greatest(1, least(coalesce(p_limit, 25), 100))
    for update skip locked
  )
  update private.storage_cleanup_queue q
  set status = 'PROCESSING',
      attempts = q.attempts + 1,
      updated_at = now()
  from due
  where q.id = due.id
  returning q.id, q.bucket_id, q.object_name, q.owner_id, q.attempts;
end;
$$;

create or replace function public.complete_storage_cleanup_job(
  p_id bigint,
  p_status text,
  p_error text default null
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  update private.storage_cleanup_queue q
  set status = case
        when p_status = 'PENDING' and q.attempts >= 8 then 'FAILED'
        else p_status
      end,
      last_error = p_error,
      next_attempt_at = case
        when p_status = 'PENDING' then now() + (power(2, least(q.attempts, 6)) || ' seconds')::interval
        else q.next_attempt_at
      end,
      updated_at = now()
  where q.id = p_id;
end;
$$;

-- 3. Issue INSERT/UPDATE/DELETE triggers, grants & RLS policies (B8)
create or replace function public.before_issue_insert()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  caller_uid uuid := (select auth.uid());
  prof record;
begin
  if caller_uid is null or new.author_id is distinct from caller_uid then
    raise exception 'Unauthorized issue author' using errcode = '42501';
  end if;

  select username, avatar_url into prof
  from public.profiles
  where id = caller_uid;

  if prof.username is not null then
    new.author_username := prof.username;
    new.author_avatar_url := prof.avatar_url;
  end if;

  new.caption := btrim(coalesce(new.caption, ''));
  if char_length(new.caption) < 5 or char_length(new.caption) > 500 then
    raise exception 'Caption must be between 5 and 500 characters' using errcode = '22023';
  end if;

  new.title := left(split_part(new.caption, E'\n', 1), 52);

  if new.category not in ('Public Works', 'Power & Lighting', 'Water & Sanitation', 'Smart City / IT', 'Roads & Transit') then
    raise exception 'Invalid issue category' using errcode = '22023';
  end if;

  new.location_name := btrim(coalesce(new.location_name, ''));
  if char_length(new.location_name) < 1 or char_length(new.location_name) > 160 then
    raise exception 'Location name must be 1 to 160 characters' using errcode = '22023';
  end if;

  new.sub_location := btrim(coalesce(new.sub_location, ''));
  if char_length(new.sub_location) > 240 then
    raise exception 'Location detail must be at most 240 characters' using errcode = '22023';
  end if;

  if new.latitude is null or new.longitude is null
     or new.latitude in ('Infinity'::double precision, '-Infinity'::double precision, 'NaN'::double precision)
     or new.longitude in ('Infinity'::double precision, '-Infinity'::double precision, 'NaN'::double precision)
     or new.latitude < -90.0 or new.latitude > 90.0
     or new.longitude < -180.0 or new.longitude > 180.0 then
    raise exception 'Invalid coordinates' using errcode = '22023';
  end if;

  if coalesce(array_length(new.media_urls, 1), 0) < 1 or new.media_urls::text like '%drawable://%' then
    raise exception 'A real photo upload URL is required' using errcode = '22023';
  end if;

  new.is_gps_verified := false;
  new.status := 'IN_PROGRESS';
  new.resolved_at := null;
  new.created_at := now();
  new.updated_at := new.created_at;
  new.is_fixture := false;

  return new;
end;
$$;

create or replace function public.before_issue_update()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  caller_uid uuid := (select auth.uid());
  is_owner boolean := (caller_uid is not null and old.author_id = caller_uid);
  is_staff boolean := private.is_category_staff(old.category);
  content_changed boolean;
  status_changed boolean;
  location_changed boolean;
  prof record;
begin
  if current_user in ('postgres', 'service_role') and (
    caller_uid is null
    or coalesce(current_setting('issuegram.profile_propagation', true), '') = 'on'
  ) then
    return new;
  end if;

  if not is_owner and not is_staff then
    raise exception 'Permission denied to update this issue' using errcode = '42501';
  end if;

  if new.id is distinct from old.id
     or new.ticket_code is distinct from old.ticket_code
     or new.request_id is distinct from old.request_id
     or new.author_id is distinct from old.author_id
     or new.author_username is distinct from old.author_username
     or new.author_avatar_url is distinct from old.author_avatar_url
     or new.media_urls is distinct from old.media_urls
     or new.media_type is distinct from old.media_type
     or new.upvotes_count is distinct from old.upvotes_count
     or new.created_at is distinct from old.created_at
     or new.is_fixture is distinct from old.is_fixture
     or new.resolved_at is distinct from old.resolved_at then
    raise exception 'Cannot modify protected issue fields' using errcode = '42501';
  end if;

  if new.is_gps_verified is distinct from old.is_gps_verified then
    raise exception 'Cannot directly modify GPS verification' using errcode = '42501';
  end if;

  content_changed := (
    new.title is distinct from old.title
    or new.caption is distinct from old.caption
    or new.category is distinct from old.category
    or new.location_name is distinct from old.location_name
    or new.sub_location is distinct from old.sub_location
    or new.latitude is distinct from old.latitude
    or new.longitude is distinct from old.longitude
  );

  status_changed := (new.status is distinct from old.status);

  if content_changed and not is_owner then
    raise exception 'Only the report author can edit report details' using errcode = '42501';
  end if;

  if status_changed and not is_staff then
    raise exception 'Only authorized department staff can update issue status' using errcode = '42501';
  end if;

  if content_changed then
    new.caption := btrim(coalesce(new.caption, ''));
    if char_length(new.caption) < 5 or char_length(new.caption) > 500 then
      raise exception 'Caption must be between 5 and 500 characters' using errcode = '22023';
    end if;

    new.title := left(split_part(new.caption, E'\n', 1), 52);

    if new.category not in ('Public Works', 'Power & Lighting', 'Water & Sanitation', 'Smart City / IT', 'Roads & Transit') then
      raise exception 'Invalid issue category' using errcode = '22023';
    end if;

    new.location_name := btrim(coalesce(new.location_name, ''));
    if char_length(new.location_name) < 1 or char_length(new.location_name) > 160 then
      raise exception 'Location name must be 1 to 160 characters' using errcode = '22023';
    end if;

    new.sub_location := btrim(coalesce(new.sub_location, ''));
    if char_length(new.sub_location) > 240 then
      raise exception 'Location detail must be at most 240 characters' using errcode = '22023';
    end if;

    if new.latitude is null or new.longitude is null
       or new.latitude in ('Infinity'::double precision, '-Infinity'::double precision, 'NaN'::double precision)
       or new.longitude in ('Infinity'::double precision, '-Infinity'::double precision, 'NaN'::double precision)
       or new.latitude < -90.0 or new.latitude > 90.0
       or new.longitude < -180.0 or new.longitude > 180.0 then
      raise exception 'Invalid coordinates' using errcode = '22023';
    end if;

    location_changed := (
      new.location_name is distinct from old.location_name
      or new.sub_location is distinct from old.sub_location
      or new.latitude is distinct from old.latitude
      or new.longitude is distinct from old.longitude
    );

    if location_changed then
      new.is_gps_verified := false;
    end if;

    select username, avatar_url into prof
    from public.profiles
    where id = old.author_id;

    if prof.username is not null then
      new.author_username := prof.username;
      new.author_avatar_url := prof.avatar_url;
    end if;
  end if;

  if status_changed then
    if new.status not in ('IN_PROGRESS', 'RESOLVED') then
      raise exception 'Invalid status value' using errcode = '22023';
    end if;

    if new.status = 'RESOLVED' then
      new.resolved_at := clock_timestamp();
    else
      new.resolved_at := null;
    end if;
  end if;

  if content_changed or status_changed then
    new.updated_at := clock_timestamp();
    if new.updated_at <= old.updated_at then
      new.updated_at := old.updated_at + interval '1 millisecond';
    end if;
  else
    new.updated_at := old.updated_at;
  end if;

  return new;
end;
$$;

create or replace function public.after_issue_delete_cleanup()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_url text;
  v_obj_path text;
  v_enqueued boolean := false;
begin
  if old.media_urls is not null then
    foreach v_url in array old.media_urls loop
      v_obj_path := private.extract_owned_storage_object_path(v_url, 'issue-media', old.author_id);
      if v_obj_path is not null then
        perform private.enqueue_storage_cleanup('issue-media', v_obj_path, old.author_id, 'issue_deleted');
        v_enqueued := true;
      end if;
    end loop;
  end if;

  if v_enqueued then
    perform private.dispatch_storage_cleanup_worker();
  end if;

  return old;
end;
$$;

do $$
begin
  if not exists (
    select 1 from pg_trigger
    where not tgisinternal
